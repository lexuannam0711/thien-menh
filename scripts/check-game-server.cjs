const { execFileSync } = require("node:child_process");
const assert = require("node:assert/strict");
execFileSync(process.execPath, [require.resolve("typescript/bin/tsc"), "-p", "apps/game-server/tsconfig.json"], { stdio: "inherit" });
(async () => {
  const mod = await import("../dist/game-server/server.js");
  process.env.SUPABASE_JWT_JWKS_URL = "https://example.invalid/auth/v1/.well-known/jwks.json";
  process.env.SUPABASE_JWT_AUDIENCE = "authenticated";
  const verifier = mod.createJwtVerifier();
  await assert.rejects(() => verifier(undefined), /missing bearer token/);
  await assert.rejects(() => verifier("Bearer malformed"));
  assert.equal(mod.extractBearer(undefined), null);
  assert.equal(mod.extractBearer("Basic abc"), null);
  assert.equal(mod.extractBearer("Bearer abc"), "abc");
  assert.equal(mod.validateMoveIntent({ type: "teleport", x: 0, y: 0 }), null);
  assert.equal(mod.validateMoveIntent({ type: "move", x: 2, y: 0 }), null);
  assert.equal(mod.validateMoveIntent({ type: "move", x: Number.NaN, y: 0 }), null);
  assert.deepEqual(mod.validateMoveIntent({ type: "move", x: 1, y: -1 }), { type: "move", x: 1, y: -1 });
  assert.equal(mod.validateCombatIntent({ type: "attack", seq: 1, comboIndex: 1, damage: 9999 }), null, "forged damage rejected");
  assert.equal(mod.validateCombatIntent({ type: "attack", seq: 1, comboIndex: 9 }), null, "combo bounds enforced");
  assert.equal(mod.validateCombatIntent({ type: "dodge", seq: 2, directionX: 2, directionY: 0 }), null, "dodge bounds enforced");
  assert.deepEqual(mod.validateCombatIntent({ type: "dodge", seq: 2, directionX: 1, directionY: 0 }), { type: "dodge", seq: 2, directionX: 1, directionY: 0 });
  assert.equal(mod.calculateDamage({ type: "attack", seq: 1, comboIndex: 2 }), 14, "damage is deterministic");
  assert.equal(mod.calculateDamage({ type: "attack", seq: 1, comboIndex: 2 }), mod.calculateDamage({ type: "attack", seq: 1, comboIndex: 2 }));
  const reject = mod.createReject("attack", "MALFORMED", "invalid", 7);
  const rejectAgain = mod.createReject("attack", "MALFORMED", "invalid", 7);
  assert.deepEqual({ ...reject, serverTimestamp: 0 }, { ...rejectAgain, serverTimestamp: 0 }, "reject is idempotent");
  assert.equal(mod.validatePartyIntent({ action: "create", requestId: "r1" }).action, "create");
  assert.equal(mod.validatePartyIntent({ action: "create", requestId: "r1", nope: 1 }), null, "party exact keys");
  assert.equal(mod.validatePartyIntent({ action: "invite", requestId: "r1", targetUserId: "not-uuid" }), null, "party UUID validation");
  const party = new mod.PartyRegistry();
  const leader = "11111111-1111-4111-8111-111111111111";
  const member = "22222222-2222-4222-8222-222222222222";
  const target = "33333333-3333-4333-8333-333333333333";
  const created = party.handle(leader, { action: "create", requestId: "c1" });
  assert.equal(created.partyId.length > 0, true);
  assert.equal(party.handle(member, { action: "invite", requestId: "i1", targetUserId: target }).ok, false, "non-member rejected");
  assert.equal(party.handle(leader, { action: "invite", requestId: "i2", targetUserId: target }).ok, true, "leader invite");
  assert.equal(party.handle(target, { action: "accept", requestId: "a1", partyId: created.partyId }).ok, true, "invite accept");
  assert.equal(party.snapshot(target).members.length, 2);
  assert.equal(party.handle(target, { action: "kick", requestId: "k1", targetUserId: leader }).ok, false, "non-leader kick rejected");
  assert.equal(party.handle(leader, { action: "invite", requestId: "i3", targetUserId: member }).ok, true);
  assert.equal(party.handle(member, { action: "accept", requestId: "a2", partyId: created.partyId }).ok, true);
  const fourth = "44444444-4444-4444-8444-444444444444";
  const fifth = "55555555-5555-4555-8555-555555555555";
  assert.equal(party.handle(leader, { action: "invite", requestId: "i4", targetUserId: fourth }).ok, true);
  assert.equal(party.handle(fourth, { action: "accept", requestId: "a4", partyId: created.partyId }).ok, true);
  assert.equal(party.handle(leader, { action: "invite", requestId: "i5", targetUserId: fifth }).ok, true);
  assert.equal(party.handle(fifth, { action: "accept", requestId: "a5", partyId: created.partyId }).code, "PARTY_FULL", "max four");
  assert.equal(party.handle(member, { action: "leave", requestId: "l1" }).ok, true, "leave cleanup");
  assert.equal(party.handle(leader, { action: "transfer_leader", requestId: "t1", targetUserId: target }).ok, true);
  assert.equal(party.handle(target, { action: "disband", requestId: "d1" }).ok, true, "leader disband");
  console.log("game-server self-check passed");
})();
