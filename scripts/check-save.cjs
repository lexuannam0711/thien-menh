const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = process.cwd();
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'than-menh-save-'));
try {
  const tsc = path.join(root, 'node_modules', 'typescript', 'bin', 'tsc');
  execFileSync(process.execPath, [tsc, 'src/game/systems/GameState.ts', '--target', 'ES2022', '--module', 'commonjs', '--moduleResolution', 'node', '--skipLibCheck', '--outDir', output], { cwd: root, stdio: 'inherit' });
  fs.writeFileSync(path.join(output, 'package.json'), '{"type":"commonjs"}');
  const { normalizeSave, getPlayerStats, gameState } = require(path.join(output, 'game', 'systems', 'GameState.js'));
  const initial = gameState.data;
  gameState.tickPlaytime(500);
  assert.equal(gameState.data.playtimeSeconds, 0.5);
  assert.equal(initial.playtimeSeconds, 0, 'playtime preserves previous snapshot');
  gameState.tickPlaytime(10000);
  assert.equal(gameState.data.playtimeSeconds, 1.5, 'background-sized delta cannot count idle time');
  for (const delta of [NaN, Infinity, -1, 0]) gameState.tickPlaytime(delta);
  assert.equal(gameState.data.playtimeSeconds, 1.5);
  global.document = { hidden: true };
  gameState.tickPlaytime(1000);
  assert.equal(gameState.data.playtimeSeconds, 1.5, 'hidden page cannot count playtime');
  delete global.document;
  assert.equal(normalizeSave(gameState.data).playtimeSeconds, 2, 'playtime survives save normalization');
  const save = normalizeSave({ version: 1, hp: -4, maxHp: 140, mp: 999, level: 999, gold: -1, quest: 'invalid', rpg: { inventory: { capacity: 24, slots: [{ itemId: 'x', quantity: -2 }] } } });
  assert.equal(save.hp, 0);
  assert.equal(save.mp, 100);
  assert.equal(save.level, 99);
  assert.equal(save.gold, 0);
  assert.equal(save.quest, 'new');
  assert.deepEqual(save.rpg.inventory.slots, []);
  assert.equal(save.checkpoint, 'village-gate');
  assert.equal(save.playtimeSeconds, 0);
  assert.deepEqual(save.storyFlags, {});
  assert.deepEqual(normalizeSave({ version: 9 }), normalizeSave({}));
  const loadout = normalizeSave({ version: 1, rpg: { skills: { unlockedSkillIds: ['tidal-surge'], equippedSlots: {}, activeDivinePower: 'water', unlockedDivinePowers: ['earth', 'water', 'invalid'] } } });
  assert.deepEqual(loadout.rpg.skills.equippedSlots, {});
  assert.equal(loadout.rpg.skills.activeDivinePower, 'water');
  assert.deepEqual(loadout.rpg.skills.unlockedDivinePowers, ['earth', 'water']);
  const invalidLoadout = normalizeSave({ version: 1, rpg: { skills: { unlockedSkillIds: ['tidal-surge'], equippedSlots: { 'slot-1': 'stone-armor' }, activeDivinePower: 'invalid' } } });
  assert.deepEqual(invalidLoadout.rpg.skills.equippedSlots, {});
  assert.equal(invalidLoadout.rpg.skills.activeDivinePower, 'earth');
  const inheritedIds = normalizeSave({ version: 1, rpg: { skills: { unlockedSkillIds: ['constructor', '__proto__'], equippedSlots: { 'slot-1': 'constructor' }, activeDivinePower: 'constructor', unlockedDivinePowers: ['constructor', '__proto__', 'earth'] } } });
  assert.deepEqual(inheritedIds.rpg.skills.unlockedSkillIds, []);
  assert.deepEqual(inheritedIds.rpg.skills.equippedSlots, {});
  assert.deepEqual(inheritedIds.rpg.skills.unlockedDivinePowers, ['earth']);
  assert.equal(inheritedIds.rpg.skills.activeDivinePower, 'earth');
  const axeSave = normalizeSave({ version: 1, level: 3, hp: 120, maxHp: 100, rpg: { equipment: { slots: { weapon: 'battle-axe' } } } });
  assert.equal(axeSave.hp, 120);
  assert.equal(axeSave.maxHp, 100);
  assert.equal(getPlayerStats(axeSave).maxHp, 120);
  const swordSave = normalizeSave({ version: 1, level: 3, mp: 115, maxMp: 100, rpg: { equipment: { slots: { weapon: 'lac-sword' } } } });
  assert.equal(swordSave.mp, 115);
  assert.equal(swordSave.maxMp, 100);
  assert.equal(getPlayerStats(swordSave).speed, 200);
  assert.equal(getPlayerStats({ ...swordSave, level: 1 }).maxMp, 100);
  assert.equal(getPlayerStats({ ...swordSave, level: 1 }).speed, 190);
  const previousStorage = global.localStorage;
  const previousSave = gameState.data;
  try {
    for (const raw of ['{broken', JSON.stringify({ version: 9, gold: 987 }), 'null', '[]']) {
      let stored = raw;
      let writes = 0;
      global.localStorage = { getItem: () => stored, setItem: (key, value) => { writes++; stored = value; } };
      gameState.load();
      gameState.save();
      assert.equal(writes, 0, 'Unreadable/unsupported save cannot be overwritten');
      assert.equal(stored, raw);
      assert.ok(gameState.loadError, 'Storage recovery warning is available to UI');
      assert.equal(gameState.hasSave, false, 'Unreadable save is not offered as Continue');
      gameState.reset();
      assert.equal(writes, 1, 'Explicit new game restores persistence');
      assert.equal(JSON.parse(stored).version, 1);
      assert.equal(gameState.loadError, null);
      assert.equal(gameState.hasSave, true, 'Successful reset creates a readable save');
    }
    global.localStorage = { getItem: () => { throw new Error('Storage denied'); }, setItem: () => assert.fail('Unreadable storage must not be written') };
    gameState.load();
    gameState.save();
    assert.ok(gameState.loadError);
    let stored = JSON.stringify({ version: 1, gold: 123, chapter: 2 });
    global.localStorage = { getItem: () => stored, setItem: (key, value) => { stored = value; } };
    gameState.load();
    assert.equal(gameState.data.gold, 123);
    assert.equal(gameState.data.chapter, 2);
    assert.equal(gameState.hasSave, true, 'Loaded save offers Continue');
    assert.equal(gameState.loadError, null);
    gameState.save();
    assert.equal(JSON.parse(stored).gold, 123);
    global.localStorage.getItem = () => null;
    gameState.load();
    assert.equal(gameState.loadError, null, 'Absent save is not corruption');
    assert.equal(gameState.data.gold, 0, 'Absent save cannot resurrect old session progress');
    assert.equal(gameState.hasSave, false, 'Absent save offers New Game');
    const inMemory = gameState.data;
    global.localStorage.setItem = () => { throw new Error('Quota exceeded'); };
    assert.doesNotThrow(() => gameState.save());
    assert.ok(gameState.saveError, 'Failed persistence warns the player');
    assert.equal(gameState.data, inMemory, 'Storage failure preserves session progress');
    global.localStorage.setItem = (key, value) => { stored = value; };
    gameState.save();
    assert.equal(gameState.saveError, null, 'Successful retry clears warning');
    assert.equal(JSON.parse(stored).gold, inMemory.gold);
    const ts = require('typescript');
    const hudModule = { exports: {} };
    const hudJavascript = ts.transpileModule(fs.readFileSync('src/game/ui/Hud.ts', 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText;
    const dependencies = { phaser: {}, '../../data/config': { BALANCE: { requiredKills: 6 } },
      '../systems/GameState': { gameState, getPlayerStats }, '../world/ChapterWorld': { getChapterWorldConfig: () => ({ bossName: 'Hổ Yêu' }) } };
    new Function('require', 'exports', hudJavascript)(id => dependencies[id] ?? {}, hudModule.exports);
    const text = () => ({ setText(value) { this.text = value; return this; }, setColor(value) { this.color = value; return this; } });
    const hud = { health: { setScale() {} }, mana: { setScale() {} }, healthLabel: text(), manaLabel: text(), statLabel: text(), questLabel: text(), zone: text(), place: 'Làng Lạc Thủy' };
    gameState.saveError = 'Quota exceeded';
    hudModule.exports.Hud.prototype.refresh.call(hud);
    assert.match(hud.zone.text, /CHƯA LƯU/);
    assert.equal(hud.zone.color, '#ffe0a3');
    gameState.saveError = null;
    hudModule.exports.Hud.prototype.refresh.call(hud);
    assert.equal(hud.zone.text, hud.place);
    gameState.loadError = 'Unsupported save';
    hudModule.exports.Hud.prototype.refresh.call(hud);
    assert.match(hud.zone.text, /CHƯA LƯU/);
    gameState.loadError = null;
    const persistedBeforeReset = stored;
    global.localStorage.setItem = () => { throw new Error('Quota exceeded'); };
    gameState.reset();
    assert.equal(stored, persistedBeforeReset, 'Failed new-game write preserves stored bytes');
    assert.equal(gameState.data.gold, 0);
    assert.equal(gameState.hasSave, false, 'Failed reset does not claim the new game is persisted');
    assert.ok(gameState.saveError, 'Failed reset keeps persistence warning');
    hudModule.exports.Hud.prototype.refresh.call(hud);
    assert.match(hud.zone.text, /CHƯA LƯU/);
  } finally {
    gameState.data = previousSave;
    if (previousStorage === undefined) delete global.localStorage;
    else global.localStorage = previousStorage;
  }
  console.log('Save normalization and overwrite protection self-check: PASS');
} finally {
  fs.rmSync(output, { recursive: true, force: true });
}

